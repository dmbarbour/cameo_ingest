def test_every_template_filled_by_its_builder():
    """Every current template, filled by its builder (prompt_values) on the fixture, leaves no
    slot unfilled, and each cut adds its template's own fragment (AR-009R3)."""
    import hashlib
    import tempfile

    from test_diagrams import large_layout

    from cameo_ingest import prompt_values as pv
    from cameo_ingest.archive import discover
    from cameo_ingest.emit import ProjectWriter
    from cameo_ingest.pipeline import load_layouts, parse_project
    from cameo_ingest.prompts import CURRENT, PART_CHARS
    from cameo_ingest.provenance import ContentInfo

    data = make_mdzip(instances_model(), large_layout())
    project = next(discover(data, "drone.mdzip"))
    ix = parse_project(project)
    with tempfile.TemporaryDirectory() as tmp:
        w = ProjectWriter(ContentInfo(hashlib.sha256(data).hexdigest(), "drone.mdzip"), project, ix, Path(tmp), {},
                          load_layouts(project, ix), (25, 6, 25))
        dia = next(iter(w.view.layouts))
        g, part, d = w.view.graph(dia), w.view.partition(dia), ix.diagrams[dia]
        pkg = next(e for e in ix.elements.values() if e.kind == "Package" and any(
            c.kind == "InstanceSpecification" for c in w.view.sections_in(e)))
        sections = w.view.sections_in(pkg)
        own, texts = w.view.section_view(pkg).text(), [w.view.section_view(e).text() for e in sections]
        filled = {
            "diagram-description": pv.diagram_description(ix, g, d),
            "module-description": pv.module_description(ix, part, 1, d),
            "diagram-synthesis": pv.diagram_synthesis(ix, part, d, ["It pumps."] * len(part.modules)),
            "image-description": pv.image_description(),
            "package-summary": pv.package_summary("\n\n".join([own, *texts])),
            "module-summary": pv.module_summary("Model::P", 1, 2, "x" * (PART_CHARS[1] + 1)),
            "package-synthesis": pv.package_synthesis("Model::P", [3, 4], own, [((1, 1), "A."), ((2, 2), None)], True),
            "instances-summary": pv.instances_summary(ix, "Model::P", own, sections, texts),
        }
    assert set(filled) == set(CURRENT)
    from cameo_ingest.enrich import with_context

    for tid, v in filled.items():  # with the context, as the enricher adds it (plan GS)
        assert "{{" not in CURRENT[tid].render(with_context(CURRENT[tid], v.values, lambda: "(none)")), tid
    small = pv.instances_summary(ix, "Model::P", own, sections, texts, part_chars=300)  # follows the part size
    assert small.values["DIGEST"].endswith(CURRENT["instances-summary"].fragment("cut"))
    assert len(small.values["DIGEST"]) <= 200 + len(CURRENT["instances-summary"].fragment("cut"))
    assert filled["instances-summary"].values["DIGEST"] != small.values["DIGEST"]
    assert filled["module-summary"].values["CUT_NOTE"] == CURRENT["module-summary"].fragment(
        "cut", limit=PART_CHARS[1], length=PART_CHARS[1] + 1) and filled["module-summary"].cut
    assert filled["diagram-description"].values["DIAGRAM"].endswith(")") and "(None)" not in filled[
        "diagram-description"].values["DIAGRAM"]


def test_a_candidate_request_classifies_its_answer(tmp_path, monkeypatch):
    """A plan GS variant asks what a package or diagram is about, with context; its answer's first
    line is its class, which the chunk's metadata keeps, and the text goes on without it."""
    from cameo_ingest import llm, prompts

    class Classifying(FakeChat):
        def complete(self, model, messages, temperature):
            super().complete(model, messages, temperature)
            asks = "on a line of its own, classify" in json.dumps(messages)
            return "**Class:** Structure\n\nWhat the drone is made of." if asks else "A diagram."

    import importlib.util

    made: list[FakeChat] = []
    monkeypatch.setattr(llm, "OpenAIChat", lambda cfg: made.append(Classifying(cfg)) or made[-1])
    for key in prompts.VARIANTS["about/context"]:  # the templates in use come back after the test
        monkeypatch.setitem(prompts.CURRENT, key, prompts.CURRENT[key])
    spec = importlib.util.spec_from_file_location("build_variant",
                                                  Path(__file__).parent.parent / "scripts" / "build_variant.py")
    script = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(script)
    src = tmp_path / "drone.mdzip"
    src.write_bytes(make_mdzip())
    out = tmp_path / "out"
    assert script.main(["about/context", str(src), "-o", str(out), "--text-model", "m", "--vision-model", "m",
                        "--no-calibrate", "--no-preflight"]) == 0
    assert prompts.CURRENT["package-summary"].key == "package-summary@v7"
    texts = [json.dumps(m) for _, m in made[0].enrichment()]
    diagram = next(t for t in texts if "classify the diagram" in t)
    assert "For context only, what the diagram's context and its shapes are" in diagram and "- [1] " in diagram
    chunks = [json.loads(line) for line in (out / "chunks.jsonl").open()]
    dia = next(c for c in chunks if c["metadata"]["kind"] == "generated:diagram_description")
    assert dia["metadata"]["about_class"] == "structure" and "Class" not in dia["text"]
    assert dia["text"].endswith("What the drone is made of.")
    assert all("about_class" not in c["metadata"] for c in chunks if not c["metadata"]["kind"].startswith("generated:"))


