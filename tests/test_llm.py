def test_llm_enrichment_is_labelled(tmp_path, fake_chat):
    src = tmp_path / "drone.mdzip"
    src.write_bytes(make_mdzip())
    out = tmp_path / "out"
    assert main([str(src), "-o", str(out), "--vision-model", "gemma-4", "--no-calibrate"]) == 0
    check_invariants(out)  # includes unique chunk ids for the two image descriptions (BASE-002)
    client = fake_chat[0]
    assert len(client.requests) == 4  # preflight, then the diagram and two images: no budget (BASE-019)
    assert [m for m, _ in client.enrichment()] == ["gemma-4"] * 3
    dia = (project_dir(out) / "diagrams/Drone_BDD.md").read_text()
    assert "generated by gemma-4; not part of the source model" in dia
    chunks = [json.loads(line) for line in (out / "chunks.jsonl").open()]
    record = (out / "run.json").read_text()
    assert json.loads(record)["options"]["vision_model"] == "gemma-4"
    assert "api_key" not in (record + (out / "manifest.json").read_text()).lower()
    gen = [c for c in chunks if c["metadata"]["kind"].startswith("generated:")]
    assert gen and all(c["metadata"]["provenance"]["derivation"]["method"] == "llm" for c in gen)
    assert sum(c["metadata"]["kind"] == "generated:image_description" for c in chunks) == 2
    extracted = [c for c in chunks if not c["metadata"]["kind"].startswith("generated:")]
    assert not any("gemma-4" in c["text"] for c in extracted)
    # Structure, not text (AR-012R2): what each answer is about, and an id its pieces share.
    ids = {c["id"] for c in extracted}
    dia_chunk = next(c for c in gen if c["metadata"]["kind"] == "generated:diagram_description")
    assert dia_chunk["metadata"]["primary_chunk"] in ids and dia_chunk["metadata"]["annotation"] == dia_chunk["id"]
    # rag/ holds the generated text too, since it says what a diagram is about (ADR-0029).
    rag = {json.loads(m.read_text())["kind"] for m in (out / "rag" / "meta").glob("*/*.json")}
    assert {"generated:image_description", "generated:diagram_description"} <= rag


def large_package_model() -> str:
    """The fixture model with a package of 40 documented classes: about 45,000 characters."""
    words = "The unit shall report its state to the operator console within the stated interval. " * 8
    classes = "".join(
        f"<packagedElement xmi:type='uml:Class' xmi:id='big{i}' name='Unit {i}'>"
        f"<ownedComment xmi:type='uml:Comment' xmi:id='bigc{i}' body='{words}'><annotatedElement xmi:idref='big{i}'/>"
        "</ownedComment></packagedElement>\n" for i in range(40))
    return MODEL.replace("<uml:Model xmi:type='uml:Model' xmi:id='m1' name='Model'>",
                         "<uml:Model xmi:type='uml:Model' xmi:id='m1' name='Model'>\n"
                         f"<packagedElement xmi:type='uml:Package' xmi:id='bigp' name='Big'>{classes}</packagedElement>")


def test_a_section_too_long_for_a_part_is_split_not_cut(tmp_path, fake_chat):
    """A section longer than a part goes in pieces, each headed by its title and which piece it
    is; every request fits, and nothing is cut (plan TC-01)."""
    import sqlite3

    from cameo_ingest.enrich import pieces, repack
    from cameo_ingest.prompts import PART_CHARS

    text = "Class Unit 7\n" + "\n".join(f"- line {i}: " + "word " * 50 for i in range(200)) + "\n\n" + "x" * 30000
    split = pieces(text)
    assert len(split) > 2 and all(len(p) <= PART_CHARS[1] for p in split)
    assert [p.split("\n")[:2] for p in split[:2]] == [["Class Unit 7", f"Piece: {i} of {len(split)}"] for i in (1, 2)]
    assert "".join(p.split("\n", 2)[2] for p in split).replace("\n", "").replace(" ", "") == \
        text.split("\n", 1)[1].replace("\n", "").replace(" ", "")  # every character of the text, in order
    assert pieces("Class Unit 7\nshort") == ["Class Unit 7\nshort"]
    assert repack(["a", "b"], ["A\nsmall", "B\nsmall"]) == [(["a", "b"], "A\nsmall\n\nB\nsmall")]
    assert [els for els, _ in repack(["a", "b"], ["A\nsmall", text])] == [["a", "b"]] + [["b"]] * (len(split) - 1)

    long_doc = "The unit shall report its state to the operator console within the stated interval. " * 400
    model = large_package_model().replace(
        "<packagedElement xmi:type='uml:Class' xmi:id='big7' name='Unit 7'>",
        "<packagedElement xmi:type='uml:Class' xmi:id='big7' name='Unit 7'>"
        f"<ownedComment xmi:type='uml:Comment' xmi:id='bigl' body='{long_doc}'><annotatedElement xmi:idref='big7'/>"
        "</ownedComment>")
    src = tmp_path / "drone.mdzip"
    src.write_bytes(make_mdzip(model))
    out = tmp_path / "out"
    assert main([str(src), "-o", str(out), "--text-model", "m", "--no-calibrate", "--no-preflight", "--no-render"]) == 0
    report = json.loads((out / "run.json").read_text())["llm"]
    assert "truncated_input" not in report["outcomes"]
    db = sqlite3.connect(store_db())
    prompts = [r[0] for r in db.execute("SELECT slots FROM requests WHERE template LIKE 'module-summary%'")]
    sections = [json.loads(x)["SECTIONS"] for x in prompts]
    assert all(len(x) <= PART_CHARS[1] for x in sections)
    assert sum("Unit 7\nPiece: " in x for x in sections) >= 3  # 34,000 characters of documentation
    assert sum(x.count("operator console") for x in sections) == 40 * 8 + 400  # every sentence, once


def test_the_part_size_is_an_option(tmp_path, fake_chat):
    """`--part-chars` sets the largest input of package text (plan TC-06): smaller parts are more
    of them, each within the size, and the size is in the projects' options."""
    import sqlite3

    src = tmp_path / "drone.mdzip"
    src.write_bytes(make_mdzip(large_package_model()))
    sizes = {}
    for chars in (None, 6000):
        os.environ["CAMEO_INGEST_CACHE"] = str(tmp_path / f"store{chars}")  # each size's own requests
        out = tmp_path / f"out{chars}"
        args = [str(src), "-o", str(out), "--text-model", "m", "--no-calibrate", "--no-preflight", "--no-render"]
        assert main(args + (["--part-chars", str(chars)] if chars else [])) == 0
        db = sqlite3.connect(store_db())
        parts = [json.loads(r[0])["SECTIONS"] for r in db.execute(
            "SELECT slots FROM requests WHERE template LIKE 'module-summary%' AND item LIKE '%bigp%'")]
        assert parts and all(len(x) <= (chars or 12000) for x in parts)
        sizes[chars] = len(parts)
        assert json.loads((out / "run.json").read_text())["options"]["part_chars"] == (chars or 12000)
    assert sizes[6000] > sizes[None]


def test_large_package_parts(tmp_path, fake_chat, monkeypatch):
    """A large package is summarized in parts, then from its parts' summaries, through runs of
    them when there are many; each part's summary is a chunk naming its elements (FU-005,
    plan DV-05)."""
    import sqlite3

    from cameo_ingest import enrich

    monkeypatch.setattr(enrich, "MAX_SUMMARIES", 2)  # so that parts are summarized in runs first
    src = tmp_path / "drone.mdzip"
    src.write_bytes(make_mdzip(large_package_model()))
    out = tmp_path / "out"
    assert main([str(src), "-o", str(out), "--text-model", "m", "--no-calibrate", "--no-preflight", "--no-render"]) == 0
    check_invariants(out)
    page = (project_dir(out) / "packages/Model__Big.md").read_text()
    assert "## Parts, summarized" in page and '<a id="part-1"></a>' in page and re.search('<a id="parts-\\d+-\\d+">', page)
    chunks = [json.loads(line) for line in (out / "chunks.jsonl").open()]
    parts = [c["metadata"]["covers"] for c in chunks if c["metadata"]["kind"] == "generated:module_summary"]
    singles = [p for p in parts if p["number"] == p["last"]]
    n = singles[0]["of"]
    assert 3 <= n <= 15 and [p["number"] for p in singles] == list(range(1, n + 1))
    assert all(p["last"] > p["number"] for p in parts if p not in singles)  # no run of a single part
    assert sorted(e for p in singles for e in p["elements"]) == sorted(f"big{i}" for i in range(40))
    assert singles[0]["anchor"] == "packages/Model__Big.md#part-1"
    # Headings read like any plain chunk's (AR-004R1), the names they cover cut to fit (AR-004R2).
    from cameo_ingest import plain as pl

    part1 = next(c for c in chunks if c["metadata"].get("covers") == singles[0])
    heading = part1["text"].split("\n", 1)[0]
    assert heading.startswith("Part summary of Package Big in Model (project drone [") and ", part 1 of " in heading
    assert ", covering Unit 0; Unit 1" in heading and heading.endswith("not part of the source model)"), heading
    assert pl.tokens(heading) <= pl.HEADING
    summary = [c for c in chunks if c["metadata"]["kind"] == "generated:summary" and c["metadata"]["element_id"] == "bigp"]
    assert summary[0]["text"].startswith("Summary of Package Big in Model (project drone [")
    assert [c["metadata"]["provenance"]["derivation"]["template"] for c in summary] == [CURRENT["package-synthesis"].key]
    db = sqlite3.connect(store_db())
    used = Counter(r[0] for r in db.execute("SELECT template FROM requests WHERE item LIKE '%bigp%'"))
    synthesis = CURRENT["package-synthesis"].key
    assert used[CURRENT["module-summary"].key] == n and used[synthesis] == len(parts) - n + 1
    prompt = db.execute("SELECT prompt FROM requests WHERE template = ? ORDER BY rowid DESC", (synthesis,)).fetchone()[0]
    assert "descriptions of the whole package" in prompt and re.search(r"\nParts \d+ to \d+: ", prompt)


def instances_model() -> str:
    """The fixture model with a package of analysis results: a run and 60 instances of Battery
    whose slots set a value, about 20,000 characters."""
    instances = "".join(
        f"<packagedElement xmi:type='uml:InstanceSpecification' xmi:id='in{i}' name='run.battery pack.cell{i}'>"
        f"<classifier xmi:idref='b2'/><slot xmi:type='uml:Slot' xmi:id='sl{i}'><definingFeature xmi:idref='a1'/>"
        f"<value xmi:type='uml:LiteralReal' xmi:id='lv{i}' value='{i % 3}.5'/></slot></packagedElement>\n"
        for i in range(60))
    run = ("<packagedElement xmi:type='uml:InstanceSpecification' xmi:id='inrun' name='run at 2026.01.01'>"
           "<classifier xmi:idref='b1'/><slot xmi:type='uml:Slot' xmi:id='slrun'><definingFeature xmi:idref='a1'/>"
           "<value xmi:type='uml:InstanceValue' xmi:id='ivrun' instance='in0'/></slot></packagedElement>\n")
    return MODEL.replace("<uml:Model xmi:type='uml:Model' xmi:id='m1' name='Model'>",
                         "<uml:Model xmi:type='uml:Model' xmi:id='m1' name='Model'>\n"
                         f"<packagedElement xmi:type='uml:Package' xmi:id='resp' name='Results'>{run}{instances}"
                         "</packagedElement>")


